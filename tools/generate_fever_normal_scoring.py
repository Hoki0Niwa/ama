"""Embed the canonical Fever-normal scoring data, without runtime cwd dependence."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT/'fever/normal_scoring_data.h'


def render():
    data = json.loads((ROOT/'data/fever/scoring.json').read_text(encoding='utf-8'))
    rows = ['// Generated by tools/generate_fever_normal_scoring.py from data/fever/scoring.json.',
            '// Source status: player measurement; local Steam score verification remains incomplete.',
            '#pragma once', '#include <array>', '#include <string_view>',
            'namespace fever::normal_scoring {',
            'struct Entry { std::string_view id; std::array<int, 19> powers; };',
            'inline constexpr Entry ENTRIES[] = {']
    for name, entry in data['characters'].items():
        assert len(entry['normal']) == 19
        rows.append('    {"'+name+'", {'+', '.join(map(str, entry['normal']))+'}},')
    rows.append('};')
    for name in ('color', 'group'):
        rows.append('inline constexpr int '+name.upper()+'[] = {'+', '.join(map(str, data['bonuses'][name]))+'};')
    rows += ['inline constexpr int MINIMUM = '+str(data['bonuses']['multiplier_min'])+';',
             'inline constexpr int MAXIMUM = '+str(data['bonuses']['multiplier_max'])+';', '}']
    return '\n'.join(rows)+'\n'


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    if args.check:
        if TARGET.read_text(encoding='utf-8') != render(): raise SystemExit('scoring header is stale')
    else: TARGET.write_text(render(), encoding='utf-8')
